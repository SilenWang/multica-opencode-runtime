#!/usr/bin/env node
// Trust Codex plugin hooks non-interactively.
//
// Codex normally asks the user to review and trust plugin lifecycle hooks
// interactively (`/hooks`). In a container that is not an option, so this
// script asks the local app-server for the hooks list (the same data the TUI
// uses) and persists the trust hashes into `$CODEX_HOME/config.toml`:
//
//     [hooks.state."<hook-key>"]
//     trusted_hash = "sha256:..."
//
// That is exactly what the TUI writes when the user picks "Trust all and
// continue", so no interactive step is required.
//
// Usage: codex-trust-plugin-hooks.mjs [plugin-prefix] [cwd]
//   plugin-prefix  trust only hooks whose plugin id starts with this
//                  (default: "ponytail@")
//   cwd            cwd to query hooks for (default: $HOME)
//
// Best-effort: exits 0 and leaves config untouched on any failure.

import { spawn } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { createInterface } from "node:readline";
import { homedir } from "node:os";

const BEGIN = "# >>> ponytail hook trust (auto-generated by entrypoint.sh) >>>";
const END = "# <<< ponytail hook trust (auto-generated by entrypoint.sh) <<<";

const pluginPrefix = process.argv[2] || "ponytail@";
const cwd = process.argv[3] || homedir();
const codexHome = process.env.CODEX_HOME || join(homedir(), ".codex");
const configPath = join(codexHome, "config.toml");

function queryHooks() {
  return new Promise((resolve) => {
    const child = spawn("codex", ["app-server"], {
      env: { ...process.env, CODEX_HOME: codexHome },
      stdio: ["pipe", "pipe", "ignore"],
    });
    const pending = new Map();
    let nextId = 1;
    let settled = false;

    const finish = (value) => {
      if (settled) return;
      settled = true;
      try {
        child.stdin.end();
      } catch {}
      child.kill();
      resolve(value);
    };

    const timer = setTimeout(() => finish(null), 20000);
    timer.unref?.();

    const rl = createInterface({ input: child.stdout });
    rl.on("line", (line) => {
      let msg;
      try {
        msg = JSON.parse(line);
      } catch {
        return;
      }
      if (msg.id !== undefined && pending.has(msg.id)) {
        const done = pending.get(msg.id);
        pending.delete(msg.id);
        done(msg);
      }
    });

    const send = (method, params) => {
      const id = nextId++;
      child.stdin.write(JSON.stringify({ jsonrpc: "2.0", id, method, params }) + "\n");
      return new Promise((res) => pending.set(id, res));
    };

    child.on("error", () => finish(null));

    (async () => {
      const init = await send("initialize", {
        clientInfo: { name: "codex-trust-plugin-hooks", version: "1.0.0" },
        capabilities: { experimental_api: true },
      });
      if (init && init.error) return finish(null);
      child.stdin.write(
        JSON.stringify({ jsonrpc: "2.0", method: "initialized", params: null }) + "\n",
      );
      const list = await send("hooks/list", { cwds: [cwd] });
      if (!list || list.error || !list.result) return finish(null);
      finish(list.result);
    })().catch(() => finish(null));
  });
}

function quoteKey(key) {
  return key.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

function stripManagedBlock(text) {
  const lines = text.split("\n");
  const kept = [];
  let inBlock = false;
  for (const line of lines) {
    if (line.trim() === BEGIN) {
      inBlock = true;
      continue;
    }
    if (line.trim() === END) {
      inBlock = false;
      continue;
    }
    if (!inBlock) kept.push(line);
  }
  return kept.join("\n").replace(/\n+$/, "") + "\n";
}

const result = await queryHooks();
if (!result || !Array.isArray(result.data)) {
  console.error("Codex hook trust: hooks/list unavailable; leaving config unchanged.");
  process.exit(1);
}

const hooks = result.data.flatMap((entry) => entry.hooks || []);
const wanted = hooks.filter(
  (hook) => typeof hook.pluginId === "string" && hook.pluginId.startsWith(pluginPrefix),
);
if (wanted.length === 0) {
  console.error(
    `Codex hook trust: no hooks found for plugin '${pluginPrefix}*' (plugin not installed?).`,
  );
  process.exit(1);
}

let base = existsSync(configPath) ? readFileSync(configPath, "utf8") : "";
base = stripManagedBlock(base);

const blocks = wanted.map(
  (hook) =>
    `[hooks.state."${quoteKey(hook.key)}"]\ntrusted_hash = "${hook.currentHash}"`,
);

const next = `${base.replace(/\n+$/, "")}\n\n${BEGIN}\n${blocks.join("\n\n")}\n${END}\n`;
writeFileSync(configPath, next);
console.log(
  `Codex hook trust: trusted ${wanted.length} hook(s) for '${pluginPrefix}*' in ${configPath}.`,
);
